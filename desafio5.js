//Adição
let valor1 = parseInt(prompt("Escolha um número de 1 à 9"));
let valor2 = parseInt(prompt("Escolha outro numero de 1 à 9"));
let resultadoAdi = valor1 + valor2;
alert(resultadoAdi);

//Subtração
let valor3 = parseInt(prompt("Escolha um número de 1 a 9"));
let valor4 = parseInt(prompt("Escolha outro numero de 1 a 9"));
let resultadoSub = valor3 - valor4;
alert(resultadoSub);


